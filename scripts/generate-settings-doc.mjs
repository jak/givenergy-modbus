#!/usr/bin/env node
/**
 * Generate website/settings.md from the settings catalogue (SETTINGS in dist/index.js).
 *
 *   npm run build && node scripts/generate-settings-doc.mjs           # write the page
 *   npm run build && node scripts/generate-settings-doc.mjs --check   # exit 1 if the page is stale
 *
 * The output is deterministic (catalogue order, no timestamps), so the generated page is committed
 * and `--check` can run in CI.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SETTINGS } from '../dist/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(root, 'website', 'settings.md');

/**
 * The `supported` predicates are functions, so their gate can't be printed from the catalogue.
 * Every gated setting needs an entry here, giving the gate per layout; the script fails if one is
 * missing or left over. Only layouts the setting has a register on are printed.
 */
const AC_SETTINGS_BLOCK_GATE = {
  single_phase:
    '`capabilities.acSettingsBlock`: `ac`, `all_in_one`, `hybrid_gen3` and `all_in_one_hybrid`, until HR 300 goes unanswered',
  three_phase: 'none',
};
const GATES = {
  exportPriority: AC_SETTINGS_BLOCK_GATE,
  inverterChargePowerPercent: AC_SETTINGS_BLOCK_GATE,
  inverterDischargePowerPercent: AC_SETTINGS_BLOCK_GATE,
  eps: AC_SETTINGS_BLOCK_GATE,
  forceOffGrid: AC_SETTINGS_BLOCK_GATE,
};

const LAYOUTS = ['single_phase', 'three_phase'];
const LAYOUT_NAMES = { single_phase: 'single-phase', three_phase: 'three-phase' };

function registerOn(definition, layout) {
  const { register } = definition;
  if (typeof register === 'number') {
    return !definition.layouts || definition.layouts.includes(layout) ? register : undefined;
  }
  return register[layout];
}

function cell(text) {
  return String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function valueText(definition) {
  switch (definition.kind) {
    case 'boolean':
      return 'boolean';
    case 'percent':
      return `${definition.min}–${definition.max} %`;
    case 'integer': {
      const unit = definition.unit ? ` ${definition.unit}` : '';
      const scale = definition.scale && definition.scale !== 1 ? ` (raw ÷ ${definition.scale})` : '';
      return `integer ${definition.min}–${definition.max}${unit}${scale}`;
    }
    case 'enum': {
      const names = Object.entries(definition.values).map(([name, raw]) => `\`${name}\` (${raw})`).join(', ');
      const writable = definition.writableValues
        ? `; writes only ${definition.writableValues.map(name => `\`${name}\``).join(', ')}`
        : '';
      return `${names}${writable}`;
    }
    case 'time':
      return '`"HH:MM"`';
    default:
      throw new Error(`unknown setting kind ${definition.kind}`);
  }
}

function accessText(definition) {
  if (definition.writable === false) return 'read only';
  if (definition.unsafe) return '**unsafe**';
  return 'safe';
}

function gateText(key, definition) {
  if (definition.supported) {
    const gate = GATES[key];
    if (!gate) throw new Error(`${key} has a supported() gate but no description in GATES`);
    const layouts = LAYOUTS.filter(layout => registerOn(definition, layout) !== undefined);
    if (layouts.length === 1) return gate[layouts[0]];
    return layouts.map(layout => `${LAYOUT_NAMES[layout]}: ${gate[layout]}`).join('; ');
  }
  if (GATES[key]) throw new Error(`GATES describes ${key}, which has no supported() gate`);
  return 'None';
}

function render() {
  const rows = Object.entries(SETTINGS).map(([key, definition]) => {
    const registers = LAYOUTS.map(layout => {
      const register = registerOn(definition, layout);
      return register === undefined ? '—' : `HR ${register}`;
    });
    const notes = definition.unsafe ? `${definition.description} **Risk:** ${definition.risk}` : definition.description;
    return [
      `\`${key}\``,
      definition.appName ?? '—',
      ...registers,
      valueText(definition),
      gateText(key, definition),
      accessText(definition),
      notes,
    ].map(cell);
  });

  const header = ['Key', 'App name', 'Single-phase', 'Three-phase', 'Values', 'Gate', 'Access', 'Description'];
  const table = [
    `| ${header.join(' | ')} |`,
    `|${header.map(() => '---').join('|')}|`,
    ...rows.map(row => `| ${row.join(' | ')} |`),
  ].join('\n');

  return `<!-- Generated by scripts/generate-settings-doc.mjs from src/catalogue/settings.ts. Do not edit. -->

# Settings Reference

Every setting in the catalogue (\`SETTINGS\`), in catalogue order. Each one is a single holding
register, read into \`getData().settings\` and written with \`setSetting(key, value)\`.

::: warning Generated page
This page is generated from \`src/catalogue/settings.ts\` by \`scripts/generate-settings-doc.mjs\`
(run by \`npm run docs\`). Edit the catalogue, not this file.
:::

- **Single-phase / Three-phase** is the holding register on each layout. **—** means the setting
  doesn't exist on that layout: \`setSetting\` doesn't accept the key there, and the snapshot's
  \`settings\` type has no such field.
- **Values** is what \`setSetting\` accepts and the snapshot reads. Percentages and integers outside
  the range throw \`RangeError\`. An enum value the inverter reports with no name reads as
  \`'unknown'\`, which can't be written.
- **Gate** is the runtime check on model and firmware. A gated setting is optional in the snapshot,
  is absent when the gate fails, and \`setSetting\` throws \`UnsupportedSettingError\` for it.
  \`inverter.supports(key)\` evaluates the gate.
- **Access**:
  - *safe*: written with \`setSetting\`;
  - *unsafe*: written only with \`unsafe_setSetting\`, because no reference implementation has
    verified the write (read the risk first);
  - *read only*: shown in the snapshot, never written.

See the [register map](./register-map) for what the settings do on the reference Gen3 and the
[migration guide](./migration-v3) for the 2.x names.

${table}
`;
}

const output = render();

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outputPath, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (current !== output) {
    console.error('website/settings.md is out of date. Run: npm run build && node scripts/generate-settings-doc.mjs');
    process.exit(1);
  }
  console.log('website/settings.md is up to date.');
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${outputPath}`);
}
